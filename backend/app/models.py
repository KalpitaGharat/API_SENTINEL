"""SQLAlchemy database models for API Sentinel.

Defines schemas for Scans, Findings, Evidence, Retest History,
and AI-assisted Explanations.
"""

import uuid
from datetime import datetime, timezone
from sqlalchemy import (
    Column,
    String,
    Integer,
    Float,
    Boolean,
    DateTime,
    ForeignKey,
    Text,
    JSON,
    UniqueConstraint,
)
from sqlalchemy.orm import relationship
from app.database import Base


def generate_uuid() -> str:
    """Generate string UUID."""
    return str(uuid.uuid4())


def utc_now() -> datetime:
    """Return timezone-aware current UTC time."""
    return datetime.now(timezone.utc)


class Scan(Base):
    """Represents an API security scan session."""

    __tablename__ = "scans"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    target_url = Column(String(2048), nullable=False)
    created_at = Column(DateTime, default=utc_now, nullable=False)
    completed_at = Column(DateTime, nullable=True)
    status = Column(String(50), default="Pending", nullable=False)  # Pending, Running, Completed, Failed
    total_findings = Column(Integer, default=0, nullable=False)
    scan_configuration = Column(JSON, default=dict, nullable=False)

    # Relationships
    findings = relationship("Finding", back_populates="scan", cascade="all, delete-orphan")
    retest_history = relationship("RetestHistory", back_populates="scan", cascade="all, delete-orphan")


class Finding(Base):
    """Represents an individual vulnerability detected during a scan."""

    __tablename__ = "findings"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    scan_id = Column(String(36), ForeignKey("scans.id", ondelete="CASCADE"), nullable=False, index=True)
    vulnerability = Column(String(255), nullable=False)
    category = Column(String(100), nullable=False)  # BOLA, AUTH, HEADERS, CONFIG
    endpoint = Column(String(1024), nullable=False)
    severity = Column(String(50), nullable=False)  # Critical, High, Medium, Low, Informational
    description = Column(Text, nullable=False)
    recommendation = Column(Text, nullable=False)
    status = Column(String(50), default="Open", nullable=False)  # Open, Resolved, Still Vulnerable, Retest Failed, Needs Review
    created_at = Column(DateTime, default=utc_now, nullable=False)

    # Relationships
    scan = relationship("Scan", back_populates="findings")
    evidence = relationship("Evidence", back_populates="finding", uselist=False, cascade="all, delete-orphan")
    retest_history = relationship("RetestHistory", back_populates="finding", cascade="all, delete-orphan")
    ai_explanation = relationship("AIExplanation", back_populates="finding", uselist=False, cascade="all, delete-orphan")


# Aliases for explicit domain model naming
ScanRecord = Scan
FindingRecord = Finding


class Evidence(Base):
    """Technical proof and request/response telemetry verifying a finding."""

    __tablename__ = "evidence"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    finding_id = Column(String(36), ForeignKey("findings.id", ondelete="CASCADE"), nullable=False, index=True, unique=True)
    test_user = Column(String(255), nullable=True)
    requested_resource = Column(String(1024), nullable=True)
    observed_status = Column(Integer, nullable=True)
    expected_status = Column(Integer, nullable=True)
    request_details = Column(JSON, default=dict, nullable=False)
    response_details = Column(JSON, default=dict, nullable=False)

    # Relationships
    finding = relationship("Finding", back_populates="evidence")


class RetestHistory(Base):
    """Historical audit log of re-verification attempts on a finding."""

    __tablename__ = "retest_history"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    scan_id = Column(String(36), ForeignKey("scans.id", ondelete="CASCADE"), nullable=False, index=True)
    finding_id = Column(String(36), ForeignKey("findings.id", ondelete="CASCADE"), nullable=False, index=True)
    previous_status = Column(String(50), nullable=False)
    new_status = Column(String(50), nullable=False)
    observed_result = Column(JSON, default=dict, nullable=False)
    verified = Column(Boolean, default=False, nullable=False)
    retested_at = Column(DateTime, default=utc_now, nullable=False)

    # Relationships
    scan = relationship("Scan", back_populates="retest_history")
    finding = relationship("Finding", back_populates="retest_history")


class AIExplanation(Base):
    """AI-assisted vulnerability explanation and remediation advice generated by Nemotron."""

    __tablename__ = "ai_explanations"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    finding_id = Column(String(36), ForeignKey("findings.id", ondelete="CASCADE"), nullable=False, index=True, unique=True)
    explanation = Column(Text, nullable=False)
    impact = Column(Text, nullable=False)
    remediation = Column(Text, nullable=False)
    model_name = Column(String(255), nullable=False)
    is_ai_generated = Column(Boolean, default=True, nullable=False)
    created_at = Column(DateTime, default=utc_now, nullable=False)

    # Relationships
    finding = relationship("Finding", back_populates="ai_explanation")


class DatasetTestSession(Base):
    """Represents a single-sample or batch API key detection testing session."""

    __tablename__ = "dataset_test_sessions"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    test_mode = Column(String(50), nullable=False)  # "single" or "batch"
    provider_filter = Column(String(100), nullable=True)
    label_filter = Column(String(50), nullable=True)
    split_used = Column(String(50), default="test", nullable=False)
    requested_sample_count = Column(Integer, default=1, nullable=False)
    completed_sample_count = Column(Integer, default=0, nullable=False)
    status = Column(String(50), default="running", nullable=False)  # "running", "completed", "failed"
    started_at = Column(DateTime, default=utc_now, nullable=False)
    completed_at = Column(DateTime, nullable=True)
    tp = Column(Integer, default=0, nullable=False)
    fp = Column(Integer, default=0, nullable=False)
    tn = Column(Integer, default=0, nullable=False)
    fn = Column(Integer, default=0, nullable=False)
    precision = Column(Float, default=0.0, nullable=False)
    recall = Column(Float, default=0.0, nullable=False)
    f1 = Column(Float, default=0.0, nullable=False)
    accuracy = Column(Float, default=0.0, nullable=False)
    duration_ms = Column(Float, default=0.0, nullable=False)
    session_summary = Column(JSON, default=dict, nullable=False)

    # Relationship
    results = relationship("DatasetTestResult", back_populates="session", cascade="all, delete-orphan")


class DatasetTestResult(Base):
    """Represents an individual sample prediction result in a testing session."""

    __tablename__ = "dataset_test_results"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    session_id = Column(String(36), ForeignKey("dataset_test_sessions.id", ondelete="CASCADE"), nullable=False, index=True)
    sample_id = Column(String(100), nullable=False, index=True)
    masked_sample = Column(String(255), nullable=False)  # strictly masked, never raw
    expected_provider = Column(String(100), nullable=False)
    detected_provider = Column(String(100), nullable=True)
    expected_label = Column(String(50), nullable=False)  # "positive" or "negative"
    predicted_label = Column(String(50), nullable=False)  # "positive" or "negative"
    test_outcome = Column(String(50), nullable=False)  # "correct_detection", "false_positive", "false_negative", "correct_rejection"
    detection_reason = Column(Text, nullable=False)
    execution_time_ms = Column(Float, default=0.0, nullable=False)
    created_at = Column(DateTime, default=utc_now, nullable=False)

    # Relationship
    session = relationship("DatasetTestSession", back_populates="results")


