class ApiTarget(Base):
    """Represents a registered API target under security management."""

    __tablename__ = "api_targets"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    name = Column(String(255), nullable=False)
    description = Column(Text, nullable=True)
    base_url = Column(String(2048), nullable=False)
    environment = Column(String(50), default="development", nullable=False)  # development, staging, production
    api_type = Column(String(50), default="REST", nullable=False)
    api_version = Column(String(50), nullable=True)
    specification_version = Column(String(50), nullable=True)  # OpenAPI 3.0.x, Swagger 2.0, etc.
    raw_spec = Column(JSON, nullable=True)
    created_at = Column(DateTime, default=utc_now, nullable=False)
    updated_at = Column(DateTime, default=utc_now, onupdate=utc_now, nullable=False)
    last_scan_at = Column(DateTime, nullable=True)

    # Relationships (cascade deletion only applies to discovered endpoints & auth profiles)
    endpoints = relationship("DiscoveredEndpoint", back_populates="target", cascade="all, delete-orphan")
    auth_profiles = relationship("TargetAuthProfile", back_populates="target", cascade="all, delete-orphan")


class DiscoveredEndpoint(Base):
    """Represents an individual endpoint discovered from an imported OpenAPI specification."""

    __tablename__ = "discovered_endpoints"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    target_id = Column(String(36), ForeignKey("api_targets.id", ondelete="CASCADE"), nullable=False, index=True)
    path = Column(String(1024), nullable=False)
    method = Column(String(20), nullable=False)  # GET, POST, PUT, DELETE, etc.
    operation_id = Column(String(255), nullable=True)
    summary = Column(String(512), nullable=True)
    description = Column(Text, nullable=True)
    tags = Column(JSON, default=list, nullable=False)
    parameters = Column(JSON, default=list, nullable=False)
    request_schema = Column(JSON, nullable=True)
    responses = Column(JSON, nullable=True)
    security_requirements = Column(JSON, nullable=True)
    is_sensitive_candidate = Column(Boolean, default=False, nullable=False)
    is_state_changing = Column(Boolean, default=False, nullable=False)
    is_selected = Column(Boolean, default=True, nullable=False)
    created_at = Column(DateTime, default=utc_now, nullable=False)

    __table_args__ = (
        UniqueConstraint("target_id", "path", "method", name="uq_target_endpoint_method"),
    )

    target = relationship("ApiTarget", back_populates="endpoints")


class TargetAuthProfile(Base):
    """Represents an authentication configuration / identity for a target (User A or User B)."""

    __tablename__ = "target_auth_profiles"

    id = Column(String(36), primary_key=True, default=generate_uuid, index=True)
    target_id = Column(String(36), ForeignKey("api_targets.id", ondelete="CASCADE"), nullable=False, index=True)
    account_label = Column(String(100), nullable=False)  # "User A" or "User B"
    authentication_type = Column(String(50), default="none", nullable=False)  # none, bearer, api_key_header, api_key_query, basic
    credential_ciphertext = Column(Text, nullable=True)  # Authenticated encrypted ciphertext (Fernet)
    credential_metadata = Column(JSON, default=dict, nullable=False)  # Masked preview, header name, prefix, etc.
    created_at = Column(DateTime, default=utc_now, nullable=False)
    updated_at = Column(DateTime, default=utc_now, onupdate=utc_now, nullable=False)

    __table_args__ = (
        UniqueConstraint("target_id", "account_label", name="uq_target_account_label"),
    )

    target = relationship("ApiTarget", back_populates="auth_profiles")

