class AuthProfileCreate(BaseModel):
    """Payload to configure authentication for an identity (User A or User B)."""
    account_label: str = Field(..., description="E.g. 'User A' or 'User B'")
    authentication_type: str = Field("none", description="none, bearer, api_key_header, api_key_query, basic")
    credential_value: Optional[str] = Field(None, description="Raw token/credential to be encrypted (never returned)")
    header_name: str = Field("Authorization", description="Header name for token/key")
    header_prefix: str = Field("Bearer", description="Prefix (e.g. Bearer, ApiKey)")
    username: Optional[str] = Field(None, description="Principal username")
    owned_resource_id: Optional[str] = Field(None, description="Object ID owned by this principal for BOLA tests")
    role: Optional[str] = Field(None, description="Principal role e.g. owner or probe")

    @model_validator(mode="before")
    @classmethod
    def normalize_auth_fields(cls, data: Any) -> Any:
        if isinstance(data, dict):
            # Normalize name -> account_label
            if "name" in data and "account_label" not in data:
                data["account_label"] = data["name"]
            # Normalize auth_type -> authentication_type
            if "auth_type" in data and "authentication_type" not in data:
                data["authentication_type"] = data["auth_type"]
            # Normalize token_or_secret or token -> credential_value
            if "token_or_secret" in data and "credential_value" not in data:
                data["credential_value"] = data["token_or_secret"]
            elif "token" in data and "credential_value" not in data:
                data["credential_value"] = data["token"]
        return data


